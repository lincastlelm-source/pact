                // Keeps `assembleRelease` working on a fresh clone. Not suitable for a build you
                // intend to keep installed: the debug key is machine-local and regenerating it
                // makes in-place updates impossible.
                logger.warn(
                    "PACT: no keystore.properties found, signing the release build with the " +
                        "debug key. See README for how to create a real signing key.",
                )
                signingConfigs.getByName("debug")
            }
        }
    }

