/**
 * Release signing.
 *
 * Credentials live in `keystore.properties` at the project root, which is gitignored along with
 * the keystore itself. When that file is absent — a fresh clone, or CI — the release build falls
 * back to debug signing so `assembleRelease` still produces something installable, and says so.
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = keystoreProperties.getProperty("storeFile")
    ?.let { rootProject.file(it).exists() } == true

